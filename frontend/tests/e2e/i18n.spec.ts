import { expect, test, login } from './fixtures'
import type { Page } from '@playwright/test'

test.use({ interfaceLocale: null, locale: 'ru-RU' })

async function language(page: Page, value: 'en' | 'ru') {
  await page.locator('footer').getByRole('combobox').click()
  await page.getByRole('option', { name: value === 'en' ? 'English' : 'Русский', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', value)
}

test('English is the default; footer selection persists through SSR, redirects and reloads', async ({ page, context }) => {
  const warnings: string[] = []
  page.on('console', (message) => {
    if (/hydration|not found.*locale|message compilation/i.test(message.text())) warnings.push(message.text())
  })
  await page.goto('/runs')
  await expect(page).toHaveURL('/login')
  await expect(page.getByRole('heading', { name: 'Sign in to Fure', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.locator('header').getByRole('combobox')).toHaveCount(0)
  await expect(page.locator('footer')).not.toContainText('Function Runtime Environment')
  let response = await context.request.get('/login')
  expect(await response.text()).toMatch(/<html[^>]*lang="en"/)
  await language(page, 'ru')
  await expect(page.getByRole('heading', { name: 'Войти в Fure', exact: true })).toBeVisible()
  expect((await context.cookies()).find(cookie => cookie.name === 'fure_locale')?.value).toBe('ru')
  response = await context.request.get('/login')
  expect(await response.text()).toMatch(/<html[^>]*lang="ru"/)
  expect(response.headers()['cache-control']).toBe('no-store')
  await page.reload()
  await expect(page.getByLabel('Логин', { exact: true })).toBeVisible()
  await language(page, 'en')
  await page.reload()
  await expect(page.getByLabel('Username', { exact: true })).toBeVisible()
  expect(warnings).toEqual([])
})

test('language changes update navigation, tabs, forms, permissions, statuses and dates without losing edits', async ({ page, context, request }) => {
  await login(context.request)
  const record = await (await request.post('/api/v1/functions', { data: { name: 'bilingual-ui', description: 'Описание пользователя' } })).json()
  const revision = await (await request.post('/api/v1/revisions', { data: {
    function_id: record.id,
    implementation: { type: 'python', code: 'async def function(input: None) -> str: return "Результат пользователя"' },
    runner_options: { type: 'inline_python', timeout: 10 }
  } })).json()
  await request.patch(`/api/v1/functions/${record.id}`, { data: { revision_id: revision.id } })
  await page.goto(`/functions/${record.id}?tab=settings`)
  await expect(page.getByRole('heading', { name: 'General settings', exact: true })).toBeVisible()
  await page.getByLabel('Description', { exact: true }).fill('Несохранённый текст')
  await language(page, 'ru')
  await expect(page.getByLabel('Описание', { exact: true })).toHaveValue('Несохранённый текст')
  await expect(page.getByRole('tab', { name: 'Настройки', exact: true })).toBeVisible()
  await expect(page.getByText('Готова к запуску', { exact: true })).toBeVisible()
  await language(page, 'en')
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Несохранённый текст')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Settings saved', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Run', exact: true }).click()
  await page.getByRole('button', { name: 'Run', exact: true }).click()
  await expect(page.getByText('Результат пользователя', { exact: false }).first()).toBeVisible()
  await expect(page.getByText('Succeeded', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'History', exact: true }).click()
  const run = (await (await request.get('/api/v1/runs', { params: { function_id: record.id, size: 1 } })).json()).items[0]
  const englishDate = await page.evaluate(value => new Intl.DateTimeFormat('en-US', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value)), run.created_at)
  await expect(page.getByRole('columnheader', { name: 'Duration', exact: true })).toBeVisible()
  await expect(page.getByRole('table')).toContainText(englishDate)
  await expect(page.getByRole('table')).toContainText(/\d+\s?ms/)
  await expect(page.getByText('1 record', { exact: true })).toBeVisible()
  await language(page, 'ru')
  const russianDate = await page.evaluate(value => new Intl.DateTimeFormat('ru-RU', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value)), run.created_at)
  await expect(page.getByRole('columnheader', { name: 'Длительность', exact: true })).toBeVisible()
  await expect(page.getByRole('table')).toContainText(russianDate)
  await expect(page.getByRole('table')).toContainText(/\d+\s?мс/)
  await expect(page.getByText('1 запись', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Версии', exact: true }).click()
  await page.getByRole('button', { name: 'Новая версия', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Python-код', { exact: true })).toHaveValue(/Результат пользователя/)
  // Close the modal to reach the footer, then reopen it in English.
  await dialog.getByLabel('Закрыть', { exact: true }).click()
  await language(page, 'en')
  await page.getByRole('button', { name: 'New version', exact: true }).click()
  await expect(dialog.getByLabel('Python code', { exact: true })).toHaveValue(/Результат пользователя/)
  await dialog.getByLabel('Close', { exact: true }).click()
  for (const [path, heading] of [['/users', 'Users'], ['/roles', 'Roles'], ['/account', 'admin'], ['/runs', 'Run history']]) {
    await page.goto(path!)
    await expect(page.getByRole('heading', { level: 1, name: heading, exact: true })).toBeVisible()
  }
  await page.goto('/account')
  await expect(page.getByText('Read functions and implementations', { exact: true })).toBeVisible()
  await language(page, 'ru')
  await expect(page.getByText('Чтение функций и реализаций', { exact: true })).toBeVisible()
})

