import { expect, test, password } from './fixtures'

test('login, role and user management, scoped keys and logout', async ({ page, request }, info) => {
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Логин', { exact: true }).fill('admin')
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Логика — в функциях.')
  await page.getByRole('link', { name: 'Роли', exact: true }).first().click()
  await page.getByRole('button', { name: 'Новая роль', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название роли', { exact: true }).fill('viewer-ui')
  await dialog.getByRole('checkbox', { name: 'Чтение функций и реализаций', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'Управление своими API-ключами', exact: true }).check()
  await dialog.getByRole('button', { name: 'Создать роль', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('table')).toContainText('viewer-ui')
  await page.getByRole('link', { name: 'Пользователи', exact: true }).first().click()
  await page.getByRole('button', { name: 'Новый пользователь', exact: true }).click()
  await dialog.getByLabel('Логин', { exact: true }).fill('viewer-ui')
  await dialog.getByLabel('Пароль', { exact: true }).fill(password)
  await dialog.getByRole('checkbox', { name: 'viewer-ui', exact: true }).check()
  await dialog.getByRole('button', { name: 'Создать пользователя', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('table')).toContainText('viewer-ui')
  await page.screenshot({ path: info.outputPath('users.png'), fullPage: true })
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Логин', { exact: true }).fill('viewer-ui')
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Логика — в функциях.')
  await expect(page.getByRole('button', { name: 'Новая функция', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Пользователи', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'viewer-ui', exact: true }).click()
  await page.getByRole('button', { name: 'Создать ключ', exact: true }).click()
  await dialog.getByLabel('Название', { exact: true }).fill('viewer-integration')
  await dialog.getByRole('checkbox', { name: 'Чтение функций и реализаций', exact: true }).check()
  await expect(dialog.getByRole('checkbox', { name: 'Управление пользователями', exact: true })).toHaveCount(0)
  const created = page.waitForResponse(response => response.url().endsWith('/api/v1/keys') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Создать ключ', exact: true }).click()
  const key = await (await created).json()
  await expect(dialog.getByText(key.secret, { exact: true })).toBeVisible()
  const result = await request.get('/api/v1/functions', { headers: { Authorization: `Bearer ${key.secret}` } })
  expect(result.status()).toBe(200)
  await dialog.getByRole('button', { name: 'Готово', exact: true }).click()
  await page.reload()
  await expect(page.getByText(key.secret, { exact: true })).toHaveCount(0)
  await page.getByRole('row').filter({ hasText: 'viewer-integration' }).getByRole('button', { name: 'Отозвать', exact: true }).click()
  await dialog.getByRole('button', { name: 'Отозвать', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect((await request.get('/api/v1/functions', { headers: { Authorization: `Bearer ${key.secret}` } })).status()).toBe(401)
  await page.screenshot({ path: info.outputPath('account.png'), fullPage: true })
})

test('manual JSON settings and public execution persist through the proxy', async ({ page, request, playwright, baseURL }) => {
  const session = await page.context().request.post('/api/v1/auth/login', { data: { username: 'admin', password }, headers: { 'X-Fure-Client': 'web' } })
  expect(session.ok()).toBeTruthy()
  const response = await request.post('/api/v1/functions', { data: { name: 'manual-ui' } })
  const record = await response.json()
  await page.goto(`/functions/${record.id}`)
  await page.getByRole('button', { name: 'Новая версия', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Реализация', exact: true }).click()
  await page.getByRole('option', { name: 'Jinja · OpenAI', exact: true }).click()
  await dialog.getByLabel('Модель', { exact: true }).fill('local-model')
  await dialog.getByLabel('Выходная схема', { exact: true }).fill('{"type":"object"}')
  await dialog.getByRole('switch', { name: 'Structured Outputs', exact: true }).uncheck()
  await dialog.getByLabel('Окончания тегов размышления', { exact: true }).fill('</think>\n</analysis>')
  const saved = page.waitForResponse(value => value.url().endsWith('/api/v1/revisions') && value.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Сохранить версию', exact: true }).click()
  const revision = await (await saved).json()
  expect(revision.runner_options.structured_outputs).toBe(false)
  expect(revision.runner_options.reasoning_end_tags).toEqual(['</think>', '</analysis>'])
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Новая версия', exact: true }).click()
  await expect(dialog.getByRole('switch', { name: 'Structured Outputs', exact: true })).not.toBeChecked()
  await expect(dialog.getByLabel('Окончания тегов размышления', { exact: true })).toHaveValue('</think>\n</analysis>')
  await dialog.getByLabel('Закрыть', { exact: true }).click()
  // Use Python for the public execution so the test does not call an LLM.
  const python = await request.post('/api/v1/revisions', { data: { function_id: record.id, implementation: { type: 'python', code: 'async def function(input: None) -> str: return "public hello"' }, runner_options: { type: 'inline_python', timeout: 10 } } })
  await request.patch(`/api/v1/functions/${record.id}`, { data: { revision_id: (await python.json()).id } })
  await page.reload()
  await page.getByRole('tab', { name: 'Настройки', exact: true }).click()
  await page.getByRole('switch', { name: 'Публичный запуск', exact: true }).check()
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  const guest = await playwright.request.newContext({ baseURL })
  try {
    await expect.poll(async () => (await request.get(`/api/v1/functions/${record.id}`)).json().then(value => value.public)).toBe(true)
    const run = await guest.post('/api/v1/run/manual-ui', { data: {} })
    expect(run.status()).toBe(200)
    expect((await run.json()).output).toBe('public hello')
    expect((await guest.get('/api/v1/runs')).status()).toBe(401)
  } finally {
    await guest.dispose()
  }
})
